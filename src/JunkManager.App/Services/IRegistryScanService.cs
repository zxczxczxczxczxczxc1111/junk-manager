using JunkManager.Core.Registry;

namespace JunkManager.App.Services;

/// <summary>
/// Всё, что окну нужно знать о сканировании реестра.
/// </summary>
/// <remarks>
/// <para>
/// Отдаёт <see cref="RegistryScanResult"/> ядра целиком, а не свой упрощённый
/// список. Своя запись из шести полей тут была, пока модуль был заглушкой, и
/// удалить по ней ничего нельзя: в ней нет ни вида реестра, ни того, значение
/// перед нами или ключ. 32- и 64-битная проекции HKLM это два РАЗНЫХ места с
/// одинаковым путём, и запись, потерявшая вид, однажды удалит соседнее.
/// </para>
/// <para>
/// Пропуски едут наружу вместе с находками по той же причине, по которой они
/// есть у файлового прохода: непрочитанная ветка и чистая ветка дают на экране
/// один и тот же ноль.
/// </para>
/// </remarks>
internal interface IRegistryScanService
{
    /// <summary>
    /// Сколько веток описано в файле источников. Показывается плашкой рядом с
    /// итогом: «найдено 0» при нуле веток это сломанная выкладка, а не чистый
    /// реестр.
    /// </summary>
    int BranchCount { get; }

    Task<RegistryScanResult> ScanAsync(IProgress<string>? hod, CancellationToken ct);
}

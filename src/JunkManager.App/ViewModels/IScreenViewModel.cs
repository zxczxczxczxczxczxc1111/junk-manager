namespace JunkManager.App.ViewModels;

/// <summary>
/// What the shell needs to know about a screen, and nothing else.
/// </summary>
/// <remarks>
/// Состояние одно на раздел и на его экран. Второе, своё, у раздела означало бы
/// рельс, показывающий «пусто», поверх экрана, показывающего ход сканирования:
/// одна и та же работа с двумя разными ответами на вопрос «что сейчас
/// происходит».
/// </remarks>
internal interface IScreenViewModel
{
    ScreenStateViewModel State { get; }

    /// <summary>
    /// Called every time the section becomes the current one.
    /// </summary>
    /// <remarks>
    /// <para>
    /// По умолчанию не делает ничего, и это не заглушка, а решение: подписываться
    /// обязан только тот экран, чьи данные МЕНЯЮТСЯ, пока на него не смотрят.
    /// Таких в продукте два, и оба меняет очистка с экрана «Файлы»: журнал, куда
    /// она дописывает строки, и занятость диска на «Обзоре», которую она
    /// уменьшает. До 06.09.2026 договора не было вовсе, журнал читался один раз
    /// при сборке окна, и человек, пришедший посмотреть, что у него удалили,
    /// видел вчерашнее до перезапуска программы.
    /// </para>
    /// <para>
    /// Экран, чьё чтение стоит дорого, подписываться НЕ должен. Проход по диску
    /// идёт минуты, и запускать его от переключения раздела значит наказывать
    /// человека за то, что он посмотрел в сторону.
    /// </para>
    /// </remarks>
    Task PriPokazeAsync(CancellationToken ct) => Task.CompletedTask;
}

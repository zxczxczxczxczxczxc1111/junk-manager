using Xunit;

namespace JunkManager.Tests.Infrastructure;

/// <summary>
/// Наборы, которые трогают состояние ВСЕЙ машины, а не свой каталог.
/// </summary>
/// <remarks>
/// <para>
/// xUnit гоняет наборы параллельно, и это правильно ровно до тех пор, пока у
/// набора есть своя песочница. Корзина, настоящий %TEMP% и ветки реестра
/// профиля общие на процесс: два набора, работающие с ними одновременно, видят
/// действия друг друга.
/// </para>
/// <para>
/// Поймано 05.09.2026 в госте. `RecycleBinZhivyeTests` снимает счётчик предметов
/// в корзине, удаляет один файл и ждёт «стало на один больше». Сквозная
/// проверка очистки в это же время сеяла свою приманку `recycled-file`, тоже в
/// корзину. Получилось «стало на два больше», и падение выглядело как дефект
/// удаления, хотя удаление отработало правильно оба раза.
/// </para>
/// <para>
/// Общая коллекция это не украшение и не осторожность вообще: она нужна ровно
/// тем наборам, у которых нет своего угла. Всё остальное продолжает идти
/// параллельно.
/// </para>
/// </remarks>
[CollectionDefinition(Imya, DisableParallelization = true)]
public sealed class ObshcheeSostoyanieMashiny
{
    public const string Imya = "общее состояние машины";
}
